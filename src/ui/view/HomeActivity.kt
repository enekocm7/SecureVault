package ui.view

import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.content.Intent
import android.os.Build
import android.os.Bundle
import androidx.activity.compose.setContent
import androidx.activity.viewModels
import androidx.appcompat.app.AppCompatActivity
import androidx.compose.runtime.collectAsState
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.core.view.WindowCompat
import com.enekocm.securevault.R
import domain.model.PasswordDto
import ui.compose.dialogs.CreatePasswordDialogContent
import ui.compose.dialogs.GeneratePasswordDialogContent
import ui.compose.dialogs.PasswordDetailDialogContent
import ui.compose.screens.HomeScreen
import ui.compose.theme.SecureVaultTheme
import ui.viewmodel.HomeViewModel
import ui.viewmodel.createPasswordFactory
import ui.viewmodel.generatePasswordFactory
import ui.viewmodel.homeFactory
import ui.viewmodel.passwordDetailFactory
import ui.viewmodel.dialogs.CreatePasswordViewModel
import ui.viewmodel.dialogs.GeneratePasswordViewModel
import ui.viewmodel.dialogs.PasswordDetailViewModel
import com.google.firebase.Firebase
import com.enekocm.securevault.SecureVaultApp

class HomeActivity : AppCompatActivity() {

    private val viewModel: HomeViewModel by viewModels { homeFactory(application) }
    private val createVm: CreatePasswordViewModel by viewModels { createPasswordFactory(application) }
    private val detailVm: PasswordDetailViewModel by viewModels { passwordDetailFactory(application) }
    private val genVm: GeneratePasswordViewModel by viewModels { generatePasswordFactory(application) }
    private val auth get() = (application as SecureVaultApp).container.firebaseAuth

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        WindowCompat.getInsetsController(window, window.decorView).isAppearanceLightStatusBars = true
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.VANILLA_ICE_CREAM) {
            @Suppress("DEPRECATION")
            window.statusBarColor = getColor(R.color.light_red)
        }

        setContent {
            SecureVaultTheme {
                val passwords by viewModel.passwords.collectAsState()
                val isLoading by viewModel.isLoading.collectAsState()
                var isSearchMode by remember { mutableStateOf(false) }
                var query by remember { mutableStateOf("") }
                var showCreate by remember { mutableStateOf(false) }
                var showGeneratorFor: String? by remember { mutableStateOf(null) }
                var detailItem by remember { mutableStateOf<PasswordDto?>(null) }
                var createInitialPassword by remember { mutableStateOf("") }

                val generated by genVm.password.collectAsState()
                val strength by genVm.passwordStrength.collectAsState()
                val genLoading by genVm.isLoading.collectAsState()
                var genIsPassphraseMode by remember { mutableStateOf(false) }

                HomeScreen(
                    passwords = passwords.sortedBy { it.name },
                    isLoading = isLoading,
                    isSearchMode = isSearchMode,
                    searchQuery = query,
                    profilePhotoUrl = if (viewModel.isLoggedIn()) auth?.currentUser?.photoUrl?.toString() else null,
                    onSearchToggle = {
                        isSearchMode = !isSearchMode
                        if (!isSearchMode) {
                            query = ""
                            viewModel.loadPasswords()
                        }
                    },
                    onSearchChange = {
                        query = it
                        viewModel.loadPasswords(it)
                    },
                    onSettings = { startActivity(Intent(this, SettingsActivity::class.java)) },
                    onAdd = { showCreate = true },
                    onCopy = { copy(it.value) },
                    onItemClick = { detailItem = it }
                )

                if (showCreate) {
                    CreatePasswordDialogContent(
                        onSave = {
                            if (it.name.isEmpty() || it.url.isEmpty() || it.username.isEmpty() || it.value.isEmpty()) {
                                android.widget.Toast.makeText(this, "Fields can not be empty", android.widget.Toast.LENGTH_LONG).show()
                            } else {
                                createVm.savePassword(it)
                                viewModel.loadPasswords()
                                showCreate = false
                            }
                        },
                        onCancel = { showCreate = false },
                        onGenerate = { showGeneratorFor = "create" }
                    )
                    if (createInitialPassword.isNotEmpty()) {
                        // applied via recreation: simplest is to keep state in dialog; handled by generator callback below
                    }
                }

                detailItem?.let { item ->
                    PasswordDetailDialogContent(
                        initial = item,
                        onSave = {
                            if (item.name == it.name) detailVm.savePassword(it)
                            else detailVm.savePassword(item.name, it)
                            viewModel.loadPasswords()
                            detailItem = null
                        },
                        onDelete = {
                            detailVm.removePassword(it)
                            viewModel.loadPasswords()
                            detailItem = null
                        },
                        onClose = { detailItem = null }
                    )
                }

                if (showGeneratorFor != null) {
                    GeneratePasswordDialogContent(
                        generated = generated,
                        strength = strength,
                        isLoading = genLoading,
                        onRegenerate = {
                            if (genIsPassphraseMode) genVm.getPassphrase(5, "-")
                            else genVm.getPassword(16, true, true, true, true)
                        },
                        onUse = { pwd ->
                            createInitialPassword = pwd
                            showGeneratorFor = null
                        },
                        onClose = { showGeneratorFor = null },
                        onGeneratePassword = { l, lo, up, n, s -> genVm.getPassword(l, lo, up, n, s) },
                        onGeneratePassphrase = { w -> genIsPassphraseMode = true; genVm.getPassphrase(w, "-") }
                    )
                }
            }
        }
    }

    override fun onResume() {
        super.onResume()
        viewModel.loadPasswords()
    }

    private fun copy(text: String) {
        val clipboard = getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
        clipboard.setPrimaryClip(ClipData.newPlainText("password", text))
        android.widget.Toast.makeText(this, getString(R.string.copyText), android.widget.Toast.LENGTH_SHORT).show()
    }
}
