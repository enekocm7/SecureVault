package ui.view.dialogs

import android.app.Dialog
import android.graphics.Color
import android.os.Bundle
import android.view.ViewGroup
import android.widget.Toast
import androidx.compose.runtime.collectAsState
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.ui.platform.ComposeView
import androidx.core.graphics.drawable.toDrawable
import androidx.fragment.app.DialogFragment
import androidx.fragment.app.FragmentManager
import androidx.fragment.app.viewModels
import androidx.lifecycle.lifecycleScope
import com.enekocm.securevault.R
import domain.model.PasswordDto
import ui.compose.dialogs.CreatePasswordDialogContent
import ui.compose.dialogs.GeneratePasswordDialogContent
import ui.compose.theme.SecureVaultTheme
import ui.view.HomeActivity
import ui.viewmodel.createPasswordFactory
import ui.viewmodel.dialogs.CreatePasswordViewModel
import ui.viewmodel.generatePasswordFactory
import ui.viewmodel.dialogs.GeneratePasswordViewModel
import kotlinx.coroutines.launch

class CreatePasswordDialog(private val supportFragmentManager: FragmentManager) : DialogFragment() {

    private val viewModel: CreatePasswordViewModel by viewModels { createPasswordFactory(requireActivity().application) }
    private val genViewModel: GeneratePasswordViewModel by viewModels { generatePasswordFactory(requireActivity().application) }

    override fun onCreateDialog(savedInstanceState: Bundle?): Dialog {
        val dialog = super.onCreateDialog(savedInstanceState).apply {
            setCancelable(false)
            setCanceledOnTouchOutside(false)
        }
        dialog.window?.setBackgroundDrawable(Color.TRANSPARENT.toDrawable())
        dialog.setContentView(
            ComposeView(requireContext()).apply {
                layoutParams = ViewGroup.LayoutParams(
                    (resources.displayMetrics.widthPixels * 0.9).toInt(),
                    ViewGroup.LayoutParams.WRAP_CONTENT
                )
                setContent {
                    SecureVaultTheme {
                        var showGen by remember { mutableStateOf(false) }
                        val generated by genViewModel.password.collectAsState()
                        val strength by genViewModel.passwordStrength.collectAsState()
                        val loading by genViewModel.isLoading.collectAsState()
                        var pendingPassword by remember { mutableStateOf<String?>(null) }

                        CreatePasswordDialogContent(
                            onSave = { dto ->
                                if (dto.name.isEmpty() || dto.url.isEmpty() || dto.username.isEmpty() || dto.value.isEmpty()) {
                                    val empty = listOf("name" to dto.name, "url" to dto.url, "username" to dto.username, "password" to dto.value)
                                        .first { it.second.isEmpty() }.first
                                    Toast.makeText(requireContext(), "$empty can not be empty", Toast.LENGTH_LONG).show()
                                } else {
                                    val finalDto = pendingPassword?.let { dto.copy(value = it) } ?: dto
                                    viewModel.savePassword(finalDto)
                                    dismiss()
                                }
                            },
                            onCancel = { dismiss() },
                            onGenerate = { showGen = true }
                        )
                        if (showGen) {
                            GeneratePasswordDialogContent(
                                generated = generated,
                                strength = strength,
                                isLoading = loading,
                                onRegenerate = { genViewModel.getPassword(16, true, true, true, true) },
                                onUse = {
                                    pendingPassword = it
                                    showGen = false
                                },
                                onClose = { showGen = false },
                                onGeneratePassword = { l, lo, up, n, s -> genViewModel.getPassword(l, lo, up, n, s) },
                                onGeneratePassphrase = { w -> genViewModel.getPassphrase(w, "-") }
                            )
                        }
                        // initial generate
                        androidx.compose.runtime.LaunchedEffect(Unit) {
                            genViewModel.getPassword(16, true, true, true, true)
                        }
                        lifecycleScope.launch {
                            // keep pending password applied by re-showing? handled via pendingPassword
                        }
                    }
                }
            }
        )
        dialog.window?.setLayout(
            (resources.displayMetrics.widthPixels * 0.9).toInt(),
            ViewGroup.LayoutParams.WRAP_CONTENT
        )
        return dialog
    }
}
